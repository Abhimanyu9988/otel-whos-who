"""Ownership Check rules against known good, bad, missing, conflicting and stale source data.

Run: python -m unittest discover -s tests
No network: every test builds its own cache directory of source files.
"""
import json
import os
import shutil
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))

import ownership as own  # noqa: E402

REPO = "open-telemetry/opentelemetry-collector-contrib"
CHECKED = "2026-10-31"
SHA = "a" * 40
ANSWERS = {own.YES, own.NO, own.NOT_SURE, own.NOT_CHECKED}

CONTRIBUTING = """# Contributing
## Membership
### Becoming a Code Owner

A Code Owner is responsible for a component within Collector Contrib, as indicated by the CODEOWNERS file.

#### Code Owners

Following the steps outlined in the documentation for the [unmaintained stability status](x), ...
"""


def metadata(cls="receiver", active=(), emeritus=(), seeking=False, levels=("beta",)):
    lines = ["type: example", "", "status:", f"  class: {cls}", "  stability:"]
    lines += [f"    {lv}: [metrics]" for lv in levels]
    lines += ["  codeowners:", f"    active: [{', '.join(active)}]"]
    if emeritus:
        lines.append(f"    emeritus: [{', '.join(emeritus)}]")
    if seeking:
        lines.append("    seeking_new: true")
    return "\n".join(lines) + "\n"


def codeowners(rows, unmaintained=()):
    out = ["# Code generated by githubgen. DO NOT EDIT.", "", "* @open-telemetry/collector-contrib-approvers", "",
           "# Start components list", ""]
    out += [f"{path}/  @open-telemetry/collector-contrib-approvers {' '.join('@' + o for o in owners)}".rstrip()
            for path, owners in rows]
    out += ["", "# End components list", "", "# Start unmaintained components list", ""]
    out += [f"{path}/  @open-telemetry/collector-contrib-approvers" for path in unmaintained]
    out += ["", "# End unmaintained components list"]
    return "\n".join(out) + "\n"


class Fixture:
    """A throwaway .cache/repos/<repo> directory."""

    def __init__(self, components, owners_file=None, contributing=CONTRIBUTING, sha=SHA):
        self.dir = tempfile.mkdtemp(prefix="whoswho-")
        files = [".github/component_labels.txt"]
        labels = "\n".join(f"{path} {label}" for path, label, _ in components) + "\n"
        self.write(".github/component_labels.txt", labels)
        for path, _, meta in components:
            if meta is not None:
                self.write(f"components/{path}/metadata.yaml", meta)
        if owners_file is not None:
            self.write(".github/CODEOWNERS", owners_file)
            files.append(".github/CODEOWNERS")
        if contributing is not None:
            self.write("CONTRIBUTING.md", contributing)
            files.append("CONTRIBUTING.md")
        self.write("meta.json", json.dumps({"branch": "main", "sha": sha, "files": files}))

    def write(self, rel, text):
        path = os.path.join(self.dir, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)

    def run(self, labels=None, snapshot=None, merged=None):
        merged = merged if merged is not None else {"rows": [], "done": True, "oldest": "9999"}
        _, results = own.check_repo(REPO, self.dir, CHECKED, activity=(labels or {}, snapshot, merged))
        return {r["path"]: {a["id"]: a for a in r["answers"]} for r in results}

    def close(self):
        shutil.rmtree(self.dir, ignore_errors=True)


def merged_rows(*rows):
    """rows: (number, merged_at, merged_by, approvers...) newest first, as load_activity returns them."""
    out = [{"repo": REPO, "number": str(n), "merged_at": day, "author": "someone", "merged_by": by,
            "approvers": ";".join(appr)} for n, day, by, *appr in rows]
    return {"rows": out, "done": True, "oldest": min((r["merged_at"] for r in out), default="9999")}


class Base(unittest.TestCase):
    def fixture(self, *a, **kw):
        fx = Fixture(*a, **kw)
        self.addCleanup(fx.close)
        return fx


class AnswerShape(Base):
    """Every answer, in every scenario, is complete and honest about its sources."""

    def test_every_answer_has_value_source_date_and_explanation(self):
        fx = self.fixture([
            ("receiver/good", "receiver/good", metadata(active=["alice"])),
            ("receiver/orphan", "receiver/orphan", metadata(active=[])),
            ("receiver/missing", "receiver/missing", None),
            ("receiver/broken", "receiver/broken", "status: [unclosed\n"),
        ], codeowners([("receiver/good", ["alice"]), ("receiver/orphan", [])]))
        res = fx.run(snapshot={"date": CHECKED})
        self.assertEqual(set(res), {"receiver/good", "receiver/orphan", "receiver/missing", "receiver/broken"})
        for path, answers in res.items():
            self.assertEqual(list(answers), list(own.QUESTIONS), path)
            for a in answers.values():
                with self.subTest(path=path, q=a["id"]):
                    self.assertIn(a["answer"], ANSWERS)
                    self.assertEqual(a["checked"], CHECKED)
                    self.assertTrue(a["summary"])
                    self.assertIn(a["basis"]["kind"], {own.PROJECT_RULE, own.OUR_RULE})
                    self.assertIsInstance(a["evidence"], list)
                    for e in a["evidence"]:
                        self.assertTrue(e["url"].startswith("https://github.com/"), e)
                    if a["status"] == own.ATTENTION:  # every problem says what, why and how
                        self.assertTrue(a["wrong"] and a["why"] and a["fix"], a)
                    for text in (a["summary"], a["wrong"], a["why"], a["fix"]):  # plain text, no raw links
                        self.assertNotIn("http", text or "")

    def test_evidence_is_pinned_to_the_commit_and_line(self):
        fx = self.fixture([("receiver/good", "receiver/good", metadata(active=["alice"]))],
                          codeowners([("receiver/good", ["alice"])]))
        a = fx.run()["receiver/good"]["lists_agree"]
        urls = [e["url"] for e in a["evidence"]]
        self.assertIn(f"https://github.com/{REPO}/blob/{SHA}/receiver/good/metadata.yaml#L7", urls)
        self.assertTrue(any(u.startswith(f"https://github.com/{REPO}/blob/{SHA}/.github/CODEOWNERS#L") for u in urls))

    def test_without_a_commit_the_branch_is_used(self):
        fx = self.fixture([("receiver/good", "receiver/good", metadata(active=["alice"]))],
                          codeowners([("receiver/good", ["alice"])]), sha=None)
        url = fx.run()["receiver/good"]["has_owner"]["evidence"][0]["url"]
        self.assertTrue(url.startswith(f"https://github.com/{REPO}/blob/main/"), url)


class HasOwner(Base):
    def test_good_named_owner(self):
        a = self.fixture([("receiver/x", "receiver/x", metadata(active=["alice", "bob"]))],
                         codeowners([("receiver/x", ["alice", "bob"])])).run()["receiver/x"]["has_owner"]
        self.assertEqual((a["answer"], a["status"]), (own.YES, own.OK))
        self.assertIn("@alice", a["summary"])

    def test_bad_user_facing_part_with_nobody(self):
        a = self.fixture([("exporter/x", "exporter/x", metadata(cls="exporter", active=[]))],
                         codeowners([("exporter/x", [])])).run()["exporter/x"]["has_owner"]
        self.assertEqual((a["answer"], a["status"]), (own.NO, own.ATTENTION))
        self.assertIn("Looking for code owners for exporter/x", a["draft"])
        self.assertEqual(a["basis"]["kind"], own.PROJECT_RULE)
        self.assertIn("CONTRIBUTING.md#L5", a["basis"]["url"])
        self.assertIn("CONTRIBUTING.md#L3", a["fixLink"]["url"])

    def test_internal_or_shared_code_is_information_not_a_problem(self):
        res = self.fixture([
            ("pkg/x", "pkg/x", metadata(cls="pkg", active=[])),
            ("receiver/r", "receiver/r", metadata(active=["dana"])),
            ("receiver/r/internal/scraper/s", "receiver/r/internal/s", metadata(cls="scraper", active=[])),
        ], codeowners([("pkg/x", []), ("receiver/r", ["dana"]), ("receiver/r/internal/scraper/s", [])])).run()
        self.assertEqual((res["pkg/x"]["has_owner"]["answer"], res["pkg/x"]["has_owner"]["status"]), (own.NO, own.INFO))
        inner = res["receiver/r/internal/scraper/s"]["has_owner"]
        self.assertEqual((inner["answer"], inner["status"]), (own.NO, own.INFO))
        self.assertIn("(receiver/r) lists @dana", inner["summary"])

    def test_nested_part_without_its_own_line_inherits_the_parent_line(self):
        a = self.fixture([("receiver/r/sub", "receiver/r/sub", metadata(active=[]))],
                         codeowners([("receiver/r", ["dana"])])).run()["receiver/r/sub"]["has_owner"]
        self.assertEqual((a["answer"], a["status"]), (own.YES, own.OK))
        self.assertIn("receiver/r: @dana", a["summary"])

    def test_team_counts_as_responsible(self):
        a = self.fixture([("internal/c", "internal/c", metadata(cls="pkg", active=["open-telemetry/collector-approvers"]))],
                         codeowners([("internal/c", ["open-telemetry/collector-approvers"])])).run()["internal/c"]["has_owner"]
        self.assertEqual(a["answer"], own.YES)

    def test_unmaintained_part_is_known_to_the_project(self):
        a = self.fixture([("receiver/old", "receiver/old",
                           metadata(active=[], emeritus=["eve"], levels=("unmaintained",)))],
                         codeowners([], unmaintained=["receiver/old"])).run()["receiver/old"]["has_owner"]
        self.assertEqual((a["answer"], a["status"]), (own.NO, own.INFO))
        self.assertIn("unmaintained", a["summary"])

    def test_missing_details_file_falls_back_to_review_list(self):
        res = self.fixture([("receiver/a", "receiver/a", None), ("receiver/b", "receiver/b", None)],
                           codeowners([("receiver/a", ["alice"]), ("receiver/b", [])])).run()
        self.assertEqual(res["receiver/a"]["has_owner"]["answer"], own.YES)
        self.assertEqual(res["receiver/b"]["has_owner"]["answer"], own.NOT_SURE)

    def test_unreadable_details_file_is_not_checked(self):
        a = self.fixture([("receiver/x", "receiver/x", "status: [unclosed\n")],
                         codeowners([("receiver/x", ["alice"])])).run()["receiver/x"]["has_owner"]
        self.assertEqual(a["answer"], own.NOT_CHECKED)

    def test_without_a_contributing_guide_the_rule_is_labelled_ours(self):
        a = self.fixture([("exporter/x", "exporter/x", metadata(cls="exporter", active=[]))],
                         codeowners([("exporter/x", [])]), contributing=None).run()["exporter/x"]["has_owner"]
