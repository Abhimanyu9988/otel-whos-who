class RecentReview(Base):
    def setUp(self):
        self.fx = self.fixture([("receiver/x", "receiver/x", metadata(active=["alice", "bob"]))],
                               codeowners([("receiver/x", ["alice", "bob"])]))

    def test_recent_approval_is_yes_with_a_pull_request_link(self):
        a = self.fx.run(merged=merged_rows((901, "2026-10-20", "zed", "ALICE"), (500, "2025-11-01", "zed")))
        a = a["receiver/x"]["recent_review"]
        self.assertEqual((a["answer"], a["status"]), (own.YES, own.OK))
        self.assertEqual(a["evidence"][0]["url"], f"https://github.com/{REPO}/pull/901")

    def test_a_merge_counts(self):
        a = self.fx.run(merged=merged_rows((7, "2026-09-01", "bob"), (1, "2025-11-01", "zed")))["receiver/x"]["recent_review"]
        self.assertEqual(a["answer"], own.YES)

    def test_no_activity_is_never_no_and_names_nobody(self):
        a = self.fx.run(merged=merged_rows((3, "2026-10-01", "zed", "yan"), (1, "2025-11-01", "alice")))
        a = a["receiver/x"]["recent_review"]
        self.assertEqual(a["answer"], own.NOT_SURE)
        self.assertNotIn("@alice", a["summary"])
        self.assertNotIn("@bob", a["summary"])
        self.assertIn("does not mean they are inactive", a["why"])

    def test_activity_older_than_the_window_does_not_count(self):
        a = self.fx.run(merged=merged_rows((2, "2026-01-01", "alice"), (1, "2025-11-01", "zed")))
        self.assertEqual(a["receiver/x"]["recent_review"]["answer"], own.NOT_SURE)

    def test_incomplete_history_is_not_checked(self):
        partial = merged_rows((3, "2026-10-01", "zed"))  # oldest row is inside the 180-day window
        self.assertEqual(self.fx.run(merged=partial)["receiver/x"]["recent_review"]["answer"], own.NOT_CHECKED)
        backfilling = dict(merged_rows((3, "2026-10-01", "zed"), (1, "2025-11-01", "zed")), done=False)
        self.assertEqual(self.fx.run(merged=backfilling)["receiver/x"]["recent_review"]["answer"], own.NOT_CHECKED)
        self.assertEqual(self.fx.run()["receiver/x"]["recent_review"]["answer"], own.NOT_CHECKED)

    def test_team_only_is_not_checked(self):
        fx = self.fixture([("internal/c", "internal/c", metadata(cls="pkg", active=["open-telemetry/collector-approvers"]))],
                          codeowners([("internal/c", ["open-telemetry/collector-approvers"])]))
        a = fx.run(merged=merged_rows((1, "2026-10-01", "x")))["internal/c"]["recent_review"]
        self.assertEqual(a["answer"], own.NOT_CHECKED)
        self.assertIn("team", a["summary"])

    def test_never_answers_no_in_any_scenario(self):
        scenarios = [None, merged_rows(), merged_rows((1, "2026-10-01", "zed")),
                     merged_rows((2, "2026-10-01", "zed"), (1, "2024-01-01", "zed")),
                     dict(merged_rows((2, "2026-10-01", "zed"), (1, "2024-01-01", "zed")), done=False)]
        for merged in scenarios:
            for path, answers in self.fx.run(merged=merged).items():
                self.assertNotEqual(answers["recent_review"]["answer"], own.NO, merged)


