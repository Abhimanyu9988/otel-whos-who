class LongWait(Base):
    def setUp(self):
        self.fx = self.fixture([("receiver/x", "receiver/x", metadata(active=["alice"]))],
                               codeowners([("receiver/x", ["alice"])]))

    def run_with(self, row, date=CHECKED):
        return self.fx.run(labels={"receiver/x": row} if row else {}, snapshot={"date": date})["receiver/x"]["long_wait"]

    def test_nothing_waiting(self):
        self.assertEqual(self.run_with(None)["answer"], own.NO)
        self.assertEqual(self.run_with({"waiting_owners": "0"})["answer"], own.NO)

    def test_recent_waits_are_normal(self):
        a = self.run_with({"waiting_owners": "2", "oldest_waiting": "2026-10-20"})
        self.assertEqual((a["answer"], a["status"]), (own.NO, own.OK))

    def test_long_wait_needs_attention(self):
        a = self.run_with({"waiting_owners": "3", "oldest_waiting": "2026-08-01"})
        self.assertEqual((a["answer"], a["status"]), (own.YES, own.ATTENTION))
        self.assertIn("91 days ago", a["summary"])
        self.assertIn("label%3A%22receiver/x%22", a["evidence"][0]["url"])

    def test_unknown_age_is_not_sure(self):
        self.assertEqual(self.run_with({"waiting_owners": "1", "oldest_waiting": ""})["answer"], own.NOT_SURE)

    def test_stale_or_missing_data_is_not_checked(self):
        self.assertEqual(self.run_with({"waiting_owners": "1", "oldest_waiting": "2026-01-01"}, date="2026-10-20")["answer"],
                         own.NOT_CHECKED)
        self.assertEqual(self.fx.run()["receiver/x"]["long_wait"]["answer"], own.NOT_CHECKED)


class Parsing(unittest.TestCase):
    def test_codeowners_sections_last_rule_wins_and_catch_all(self):
        rules = own.parse_codeowners(codeowners([("receiver/x", ["a"]), ("receiver/x", ["b"])], unmaintained=["receiver/old"]))
        self.assertEqual(rules["receiver/x"]["users"], ["b"])
        self.assertTrue(rules["receiver/old"]["unmaintained"])
        self.assertFalse(rules["receiver/x"]["unmaintained"])
        self.assertEqual(rules["*"]["owners"], ["open-telemetry/collector-contrib-approvers"])

    def test_metadata_view(self):
        v = own.metadata_view(metadata(cls="exporter", active=["a"], emeritus=["b"], seeking=True, levels=("unmaintained",)))
        self.assertEqual((v["class"], v["active"], v["emeritus"], v["seeking_new"], v["unmaintained"]),
                         ("exporter", ["a"], ["b"], True, True))
        self.assertIsNone(own.metadata_view("status: [unclosed\n"))
        self.assertIsNone(own.metadata_view("- just\n- a list\n"))


